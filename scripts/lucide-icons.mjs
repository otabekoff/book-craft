// Generates Lucide icons (ISC) for the parts of Book Craft without a build step:
//   crates/reader/ui/icons.js         SVG strings for the reader's controls
//   crates/book-core/runtime/icons.css  --bc-i-<name> mask images for book blocks
// Run: bun run lucide-icons
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "node_modules", "@lucide", "vue", "dist", "esm", "icons");

const READER = [
  "menu", "book-open", "search", "bookmark", "bookmark-plus", "a-large-small", "info", "x", "chevron-left",
  "arrow-left", "arrow-right", "trash", "sun", "moon", "monitor", "coffee", "house", "minus", "square", "copy",
  "check", "type", "list-tree", "rotate-ccw", "maximize", "minimize", "focus", "scroll-text", "book-open-text",
];

// Block name → Lucide icon.
const BLOCKS = {
  note: "info",
  info: "info",
  tip: "lightbulb",
  warning: "triangle-alert",
  caution: "triangle-alert",
  danger: "octagon-alert",
  important: "circle-alert",
  success: "circle-check",
  question: "circle-question-mark",
  example: "flask-conical",
  definition: "book-a",
  theorem: "sigma",
  proof: "square-check",
  remark: "message-square-text",
  summary: "list",
  keypoints: "sparkles",
  objectives: "target",
  history: "scroll-text",
  quiz: "list-checks",
  exercise: "pencil-line",
  hint: "lightbulb",
  solution: "circle-check-big",
  chevron: "chevron-right",
  copy: "copy",
  check: "check",
  play: "play",
  file: "file-text",
  aside: "notebook-text",
  terminal: "square-terminal",
  flip: "rotate-ccw",
  quote: "quote",
};

async function svg(name, stroke) {
  const { __iconData } = await import(pathToFileURL(join(dir, `${name}.mjs`)).href);
  const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
  const inner = __iconData.node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${esc(v)}"`).join(" ")}/>`)
    .join("");
  return stroke
    ? `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`
    : `<svg viewBox="0 0 24 24" aria-hidden="true">${inner}</svg>`;
}

const reader = {};
for (const name of READER) reader[name] = await svg(name, false);
writeFileSync(
  join(root, "crates", "reader", "ui", "icons.js"),
  `/* Generated by scripts/lucide-icons.mjs from Lucide (ISC license). Do not edit. */\nwindow.ReaderIcons = ${JSON.stringify(reader, null, 2)};\n`
);

let css = "/* Generated by scripts/lucide-icons.mjs from Lucide (ISC license). Do not edit.\n   Use as: mask-image: var(--bc-i-tip); */\n:root {\n";
for (const [key, name] of Object.entries(BLOCKS)) {
  const data = encodeURIComponent(await svg(name, true)).replace(/'/g, "%27");
  css += `  --bc-i-${key}: url("data:image/svg+xml,${data}");\n`;
}
css += "}\n";
writeFileSync(join(root, "crates", "book-core", "runtime", "icons.css"), css);
console.log(`Wrote ${READER.length} reader icons and ${Object.keys(BLOCKS).length} block icons`);
