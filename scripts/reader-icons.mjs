// Generates crates/reader/ui/icons.js from @lucide/vue so the reader (which has no
// build step) uses the same Lucide icons as the studio. Run: bun run reader-icons
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "node_modules", "@lucide", "vue", "dist", "esm", "icons");
const names = [
  "menu", "book-open", "search", "bookmark", "bookmark-plus", "a-large-small", "info", "x", "chevron-left",
  "arrow-left", "arrow-right", "trash", "sun", "moon", "monitor", "coffee", "house", "minus", "square", "copy",
];

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const icons = {};
for (const name of names) {
  const { __iconData } = await import(pathToFileURL(join(dir, `${name}.mjs`)).href);
  const parts = __iconData.node; // [tag, attrs] pairs
  const inner = parts
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${esc(v)}"`).join(" ")}/>`)
    .join("");
  icons[name] = `<svg viewBox="0 0 24 24" aria-hidden="true">${inner}</svg>`;
}

const out = `/* Generated by scripts/reader-icons.mjs from Lucide (ISC license). Do not edit. */
window.ReaderIcons = ${JSON.stringify(icons, null, 2)};
`;
writeFileSync(join(root, "crates", "reader", "ui", "icons.js"), out);
console.log(`Wrote ${names.length} icons to crates/reader/ui/icons.js`);
